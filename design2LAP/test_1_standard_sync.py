"""Test 1: wait for all tools, then prefill the whole tool context once."""

import argparse

from lap_benchmark import run_benchmark


def build_parser():
    parser = argparse.ArgumentParser(description="Test 1: standard sync prefill after all tools return.")
    parser.add_argument("--dataset_path", type=str, required=True, help="Path to async dataset (JSONL).")
    parser.add_argument("--model_path", type=str, default=None, help="Optional checkpoint path.")
    parser.add_argument("--num_samples", type=int, default=100, help="Number of samples to evaluate.")
    parser.add_argument("--reencode_num", type=int, default=5, help="Number of link tokens per segment.")
    parser.add_argument("--attn_type", type=str, default="blocked", choices=["standard", "blocked"], help="Attention type.")
    parser.add_argument("--hf", action="store_true", help="Load model_path as a HuggingFace checkpoint.")
    parser.add_argument("--primary_metric", type=str, default="strict_em", choices=["strict_em", "decomposed_pass", "llm_judge_pass"], help="Metric used for the top-level accuracy field.")
    parser.add_argument("--judge_model_path", type=str, default=None, help="Optional LLM judge model path.")
    parser.add_argument("--judge_max_new_tokens", type=int, default=128, help="Maximum tokens generated by the LLM judge.")
    parser.add_argument("--output_dir", type=str, required=True, help="Output directory for results.")
    return parser


if __name__ == "__main__":
    run_benchmark(
        build_parser().parse_args(),
        schedule_name="sync",
        display_name="Test 1: Streamed baseline - wait for all tools before prefill",
        output_prefix="test1_standard_sync",
    )